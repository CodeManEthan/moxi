@pytest.mark.parametrize("kind", ["hook", "permission", "mcp"])
def test_an_update_of_an_entry_the_user_had_first_keeps_its_file(lo, kind):
    opencode_row()
    if kind == "hook":
        write(lo, '[user]\nhooks = ["guard-rm"]\n' + HOOK)
        assert install.install().code == 0
        path = settings()
        bare = json.loads(path.read_text())
        ledger_data = ledger.read()
        ledger_data["entries"] = []                # the group was his, equal to loadout's
        ledger.write(ledger_data)
        path.write_text(json.dumps(bare))
        changed = HOOK.replace("timeout = 10", "timeout = 20")
        text = '[user]\nhooks = ["guard-rm"]\n' + changed
    elif kind == "permission":
        path = harness.settings_file("opencode")
        path.parent.mkdir(parents=True)
        path.write_text('{"permission": {"bash": {"git status*": "allow"}}}')
        write(lo, '[user]\npermissions = ["git-reads"]\n[permissions.git-reads]\n'
                  'allow = [{ shell = ["git", "status"] }]\n'
                  '[permissions.git-reads.opencode]\n')
        text = ('[user]\npermissions = ["git-reads"]\n[permissions.git-reads]\n'
                'ask = [{ shell = ["git", "status"] }]\n')
    else:
        path = harness.settings_file("opencode")
        path.parent.mkdir(parents=True)
        path.write_text('{"mcp": {"docs": {"type": "remote", '
                        '"url": "https://example.invalid/m"}}}')
        write(lo, EDITS["JSON mcp server"][0])
        text = EDITS["JSON mcp server"][0].replace("/m", "/n")
    assert install.install().code == 0
    records = [r for r in ledger.read()["entries"] if r["file"] == str(path)]
    assert records and all(r["prior"] for r in records)
    before = path.read_bytes()
    write(lo, text)
    out = install.install()
    assert out.code == 0, out.text()
    assert path.read_bytes() != before
    assert_kept(out, path, before)


