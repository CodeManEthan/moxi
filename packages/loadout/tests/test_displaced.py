@pytest.mark.skipif(os.name != "posix", reason="Windows takes no write away by a folder's mode")
def test_no_copy_no_write(lo, monkeypatch):
    write(lo, '[user]\nagents = ["helper"]\nhooks = ["guard-rm"]\n' + HOOK)
    assert install.install().code == 0
    with open(generated(), "a") as fh:
        fh.write("# my edit\n")
    data = json.loads(settings().read_text())
    data["hooks"]["PreToolUse"][0]["hooks"][0]["timeout"] = 60
    settings().write_text(json.dumps(data))
    agent, hooks = generated().read_bytes(), settings().read_bytes()
    root = displaced.root()
    root.mkdir(parents=True, exist_ok=True)
    root.chmod(0o500)                              # displaced/ can't be written
    try:
        out = install.install(replace=["agent:helper@codex", "hook:guard-rm@claude"])
    finally:
        root.chmod(0o700)
    assert out.code != 0 and out.kept == []
    assert generated().read_bytes() == agent and settings().read_bytes() == hooks
    found = states(out)
    assert found[("agent", "helper", "codex")] == "modified"
    assert found[("hook", "guard-rm", "claude")] != "ok"
    assert any("couldn't be kept" in line for line in out.lines)


