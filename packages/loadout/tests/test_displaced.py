def test_a_header_less_generated_file_reads_modified_and_every_other_run_leaves_it(
        lo, tmp_path):
    proj = tmp_path / "proj"
    proj.mkdir()
    write(lo, f'[user]\nagents = ["helper"]\nskills = ["review"]\n[project.{toml_string(proj)}]\n'
              'skills = ["review"]\n')
    assert install.install().code == 0
    generated().write_text("name = 'mine'\n")   # rewritten by hand, no header
    mine = generated().read_bytes()
    assert states(install.status())[("agent", "helper", "codex")] == "modified"
    for run in (lambda: install.install(), lambda: install.install(Scope(user=True)),
                lambda: install.install(Scope(projects=(str(proj),))),
                lambda: install.install(replace=["skill:review@claude"])):
        run()
        assert generated().read_bytes() == mine
    assert copies() == []
    out = install.install(replace=["agent:helper@codex"])
    assert out.code == 0, out.text()
    assert b"generated by moxi loadout" in generated().read_bytes()
    assert_kept(out, generated(), mine, ident="agent:helper@codex")


