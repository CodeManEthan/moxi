def git(cwd, *args, env=None) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True,
                          check=True, env=env)


def work_tree(path):
    path.mkdir(parents=True, exist_ok=True)
    git(path, "init", "-q")
    return path


def untracked(root) -> list[str]:
    out = git(root, "status", "--porcelain", "--untracked-files=all").stdout
    return [line[3:] for line in out.splitlines()]


def states(outcome) -> dict:
    return {(r.kind, r.name, r.harness): (r.state, r.reason) for r in outcome.rows}


@pytest.fixture
def lo(folder):
    kit.configure(folder)
