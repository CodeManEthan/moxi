# -- the file, without git ----------------------------------------------------------------

def test_the_ignore_file_ignores_itself_and_reads_back(tmp_path):
    data = ignores.text(["b", "a"])
    lines = data.splitlines()
    assert lines[0].startswith("# generated by moxi loadout; sha256 ")
    assert lines[1:] == ["/.gitignore", "/.*.moxi-tmp", "/.moxi-probe-*", "/a", "/b"]
    path = tmp_path / ".gitignore"
    assert ignores.state(path) == "absent"
    path.write_text(data)
    assert ignores.state(path) == "ours"
    assert ignores.listed(path) == {"a", "b"}
    path.write_text(data + "/c\n")
    assert ignores.state(path) == "edited"
    path.write_text("/a\n")
    assert ignores.state(path) == "theirs"


def test_outside_a_work_tree_nothing_is_written(lo, tmp_path):
    root = tmp_path / "plain"
    root.mkdir()
    kit.manifest(lo, f'[project."{root}"]\nskills = ["review"]\n')
    assert install.install().code == 0
    assert not (root / ".claude" / "skills" / ".gitignore").exists()
    assert ignores.records(ledger.read()) == {}


def test_an_ignore_file_whose_header_is_gone_becomes_the_users(tmp_path):
    folder = tmp_path / "skills"
    data: dict = {"entries": []}
    assert ignores.write(str(folder), ["review"], data, "user", say=lambda line: None) \
        is None
    path = folder / ".gitignore"
    mine = "/review\n/notes\n"   # the user folded loadout's line into their own
    path.write_text(mine)
    assert ignores.state(path) == "theirs"
    assert ignores.problems(data) == []
    said: list[str] = []
    assert ignores.settle(data, [], None, say=said.append) == []
    assert ignores.records(data) == {}
    assert path.read_text() == mine
    assert len(said) == 1 and "drop loadout's lines" in said[0] and "delete" not in said[0]


