"""The harness writers: hooks, permission rules, MCP servers and the managed global file.

Rule: an entry is loadout's when its ledger record locates it, and loadout removes only
what it added. Each entry is found, whatever its content, by its identity: the harness's
own key where one exists (an MCP server's name, an OpenCode permission's key path, the
Codex rules file, the Codex global block's markers), the entry itself where it is a string
(a Claude permission string, an OpenCode `instructions` path, Claude's `@` line), else a
sidecar, the record of exactly what was written (a hook group, found by its event, matcher
and command). A record in the ledger's `entries` is
`{item, harness, file, kind, key, written, prior}` (an MCP server sent through a CLI also
keeps what was `sent`, since `written` is what the CLI wrote, read back).

Every run plans every entry the manifest lists, whatever the scope; a scope applies fewer.
A refused harness file, a missing CLI or a global text that can't be read leaves its
entries as they stand, and only a dropped or disabled item plans a remove. Per entry:

- **Recorded**: found equal to what was written: `ok`, or updated in place when the
  manifest now wants something else; removed when the item is dropped or disabled.
  Found different: `modified`, left and reported; `--replace` rewrites it (or removes it
  when the item is gone). Not found: handled as unrecorded.
- **Unrecorded**: absent: added. Equal to what loadout would write: `ok`, recorded as
  `prior`, the user's first, so loadout drops its record later and never removes it.
  Different: `blocked`; `--replace <kind>:<name>@<harness>` takes it over.
- **Shared**: two items that write one entry each keep a record, and the entry goes with
  its last record. Two items wanting different values under one key: the second is
  `blocked`, naming the first.

A hook near-match (its event, matcher and command there, the rest edited) is shown with
the group found; `--replace` rewrites it only while the group still holds the recorded
command, else drops the record and adds loadout's group beside it.

Writes: the CLI-backed MCP servers first (`claude mcp add-json --scope user`, `codex mcp
add`), each read back from the file the CLI wrote; then each harness file is read once,
every kind's entries planned together, and written once (`moxi_loadout.harness.write`).
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
from dataclasses import dataclass, field
from pathlib import Path

from moxi.exit import ERROR, REFUSED

from moxi_loadout import harness as hz
from moxi_loadout.manifest import USER, expand, expand_command
from moxi_loadout.planner import Row

#: How long a harness CLI may take, in seconds.
CLI_SECONDS = 30.0
_MISSING = object()
#: The kinds whose entry is one member of a list (or a line of a text file).
MEMBERS = ("permission", "instructions", "global-line")
#: Each permission list and its decision in the Codex and OpenCode forms.
DECISIONS = {"allow": ("allow", "allow"), "ask": ("prompt", "ask"),
             "deny": ("forbidden", "deny")}
BLOCK_START = "<!-- moxi loadout: from {}; edit there -->"
BLOCK_END = "<!-- moxi loadout end -->"
RULES_HEADER = ("# generated by moxi loadout; sha256 {}; edit loadout.toml, then run moxi "
                "loadout install\n")
GLOBAL = ("global", "global")
#: The kinds of `entries` record these writers neither plan nor rewrite: the ignore files
#: of the would-commit check (`moxi_loadout.ignores`) and the opencode row in the core's
#: harness table (`moxi_loadout.harness_row`).
KEPT_ELSEWHERE = ("ignore-file", "harness-row")


@dataclass
class Entry:
    """One entry loadout wants written. `key` locates it in its file; for a member kind
    its last part is the member itself."""

    item: str
    harness: str
    file: str
    kind: str
    key: list
    value: object
    sent: object = None
    by: tuple = ()   # the items' names behind a whole-file entry (the Codex rules file)

    def ident(self) -> tuple[str, str]:
        kind, _, name = self.item.partition(":")
        return kind, name

    def location(self) -> tuple:
        return (self.file, self.kind, json.dumps(self.key))


@dataclass
class Action:
    """What a run does with one entry: `op` is `ok`, `add`, `update`, `remove`, `end`
    (drop the record only), `modified`, `blocked` or `stand` (left as it stands)."""

    entry: Entry | None
    record: dict | None
    op: str
    reason: str = ""
    prior: bool = False
    replace: object = _MISSING   # the member a --replace rewrites, for a hook
    done: bool = False
    written: object = _MISSING   # an MCP server as its CLI wrote it, read back
    follows: Action | None = None   # another item's action on the same entry
    shared: bool = False   # an `end` whose entry another wanted item keeps

    @property
    def where(self) -> Entry | dict:
        return self.entry if self.entry is not None else self.record


@dataclass
class Run:
    actions: list[Action] = field(default_factory=list)
    rows: list[Row] = field(default_factory=list)
    lines: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    docs: dict = field(default_factory=dict)
    refused: dict = field(default_factory=dict)
    shown: dict = field(default_factory=dict)   # file -> (before, after) bytes


# -- what the manifest wants ---------------------------------------------------------------

def wanted(manifest, folder, rows: dict, run: Run) -> tuple[list[Entry], set]:
    """Every entry the manifest wants, and the (item, harness) pairs it wants but can't
    build this run, whose records are carried as they stand."""
    out: list[Entry] = []
    carried: set = set()
    every = [h for h in rows]
    user = manifest.user
    for kind in ("hook", "permissions", "mcp"):
        for name in user.names(kind):
            table = manifest.item(kind, name)
            listed = manifest.harnesses(kind, name)
            for h in (every if listed is None else listed):
                item = f"{kind}:{name}"
                if user.is_disabled(kind, name, h):
                    run.rows.append(Row(USER, kind, name, h, "off", "disabled"))
                    continue
                if h not in rows:
                    carried.add((item, h))
                    run.lines.append(f"{kind} {name}: harness {h} has no row in the "
                                     "harness table; its entries are left as they stand")
                    continue
                if h not in hz.HARNESSES:
                    run.notes.append(f"{kind} {name}: loadout writes nothing for {h}")
                    continue
                try:
                    out += _build(kind, name, table, h, folder, run)
                except _Carry as exc:
                    carried.add((item, h))
                    run.rows.append(Row(USER, kind, name, h, "blocked", str(exc), None,
                                        REFUSED))
    rules = [e for e in out if e.kind == "rule-line"]
    out = [e for e in out if e.kind != "rule-line"]
    if rules:
        body = "".join(e.value + "\n" for e in rules)
        text = RULES_HEADER.format(hashlib.sha256(body.encode()).hexdigest()) + body
        out.append(Entry("permissions:*", "codex", str(hz.rules_file()), "rules", [], text,
                         by=tuple(sorted({e.ident()[1] for e in rules}))))
    out += _global(manifest, rows, run, carried)
    return out, carried


class _Carry(Exception):
    pass


def _build(kind, name, table, h, folder, run) -> list[Entry]:
    item = f"{kind}:{name}"
    if kind == "hook":
        if h == "opencode":
            run.notes.append(f"hook {name}: not for opencode, which extends by plugins")
            return []
        matcher = table.get("matcher")
        handler = {"type": "command", "command": expand_command(table["command"], folder)}
        if table.get("timeout") is not None:
            handler["timeout"] = table["timeout"]
        group = ({"matcher": matcher} if matcher else {}) | {"hooks": [handler]}
        if h == "codex":
            run.notes.append(f"hook {name}: codex runs a new hook only once you trust it "
                             "in codex")
        return [Entry(item, h, str(hz.settings_file(h)), "hook",
                      [table["event"], matcher or "", handler["command"]], group)]
    if kind == "permissions":
        return _permissions(item, name, table, h)
    return [_mcp(item, name, table, h, folder)]


def _permissions(item, name, table, h) -> list[Entry]:
    out = []
    native = table.get(h) or {}
    if h == "claude":
        path = str(hz.settings_file("claude"))
        for lst in DECISIONS:
            strings = [f"Bash({' '.join(r['shell'])}:*)" for r in table.get(lst, ())]
            strings += list(native.get(lst, ()))
            out += [Entry(item, h, path, "permission", ["permissions", lst, s], s)
                    for s in strings]
    elif h == "codex":
        unknown = sorted(set(native) - {"rules"})
        if unknown:
            raise _Carry(f"permissions.{name}.codex: unknown key {unknown[0]}; it takes "
                         "rules, a list of lines for the rules file")
        for lst, (decision, _) in DECISIONS.items():
            for r in table.get(lst, ()):
                pattern = json.dumps(list(r["shell"]))
                out.append(Entry(item, h, "", "rule-line", [],
                                 f'prefix_rule(pattern={pattern}, decision="{decision}")'))
        out += [Entry(item, h, "", "rule-line", [], str(line))
                for line in native.get("rules", ())]
    else:
        path = str(hz.settings_file("opencode"))
        for lst, (_, decision) in DECISIONS.items():
            for r in table.get(lst, ()):
                pattern = " ".join(r["shell"]) + "*"
                out.append(Entry(item, h, path, "opencode-permission",
                                 ["permission", "bash", pattern], decision))
        for key, value in native.items():
            out.append(Entry(item, h, path, "opencode-permission", ["permission", key],
                             value))
    return out


def _mcp(item, name, table, h, folder) -> Entry:
    args = [expand(a, folder) for a in table.get("args", ())]
    env = {k: expand(v, folder) for k, v in (table.get("env") or {}).items()}
    url, headers = table.get("url"), dict(table.get("headers") or {})
    if h == "claude":
        sent = ({"type": "http", "url": url} | ({"headers": headers} if headers else {})
                if url else {"type": "stdio", "command": table["command"], "args": args,
                             "env": env})
        return Entry(item, h, str(hz.claude_json()), "mcp", ["mcpServers", name], None,
                     sent)
    if h == "codex":
        if headers:
            raise _Carry(f"mcp {name}: codex mcp add takes no headers; list it for "
                         "claude and opencode only, or set harnesses")
        sent = {"url": url} if url else {"command": table["command"], "args": args,
                                         "env": env}
        return Entry(item, h, str(hz.codex_home() / "config.toml"), "mcp",
                     ["mcp_servers", name], None, sent)
    value = ({"type": "remote", "url": url} | ({"headers": headers} if headers else {})
             if url else {"type": "local", "command": [table["command"], *args]}
             | ({"environment": env} if env else {}))
    return Entry(item, h, str(hz.settings_file("opencode")), "opencode-mcp", ["mcp", name],
                 value)


def _global(manifest, rows, run, carried) -> list[Entry]:
    """The managed global file's entries; nothing for `off` and `if-absent` (the placer
    places that one)."""
    if manifest.global_mode != "managed":
        return []
    path = manifest.global_file
    try:
        text = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        for h in rows:
            carried.add(("global:global", h))
        run.rows.append(Row(USER, "global", "global", "*", "bad-source",
                            f"{path} can't be read ({exc}); the global file is left as "
                            "it stands", None, ERROR))
        return []
    out = []
    for h in rows:
        if h not in hz.HARNESSES:
            continue
        target = str(hz.global_file(h))
        if os.path.islink(target) and os.path.realpath(target) == os.path.realpath(path):
            carried.add(("global:global", h))
            run.lines.append(f"{target} links to {path}; loadout leaves it")
            continue
        if h == "claude":
            line = f"@{os.path.abspath(path)}"
            out.append(Entry("global:global", h, target, "global-line", [line], line))
        elif h == "codex":
            block = (BLOCK_START.format(os.path.abspath(path)) + "\n" + text.rstrip("\n")
                     + "\n" + BLOCK_END)
            out.append(Entry("global:global", h, target, "global-block", ["block"], block))
        else:
            out.append(Entry("global:global", h, str(hz.settings_file("opencode")),
                             "instructions", ["instructions", os.path.abspath(path)],
                             os.path.abspath(path)))
    return out


# -- reading an entry in its file ----------------------------------------------------------

def _doc(run: Run, file: str, kind: str):
    if file in run.refused:
        return None
    if file not in run.docs:
        try:
            if kind == "mcp" and file.endswith(".toml"):
                run.docs[file] = _TomlView(Path(file))
            else:
                text = kind in ("global-line", "global-block", "rules")
                run.docs[file] = hz.Doc(Path(file), "text" if text else "json")
        except hz.Refused as exc:
            run.refused[file] = str(exc)
            run.lines.append(str(exc))
            return None
    return run.docs[file]


class _TomlView:
    """Codex's `config.toml`, read only: the `codex` CLI writes its MCP servers."""

    kind = "toml"

    def __init__(self, path: Path):
        import tomllib

        self.path = path
        try:
            self.data = tomllib.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            self.data = {}
        except (OSError, ValueError) as exc:
            raise hz.Refused(f"{path} can't be read as TOML ({exc})") from None


def _get(doc, kind: str, key: list):
    if kind == "global-block":
        found = _block(doc.data)
        return _MISSING if found is None else doc.data[found[0]:found[1]]
    if kind == "rules":
        return _MISSING if doc.raw is None else doc.data
    node = doc.data
    for part in key:
        if not isinstance(node, dict) or part not in node:
            return _MISSING
        node = node[part]
    return node


def _set(doc, kind: str, key: list, value) -> None:
    if kind == "global-block":
        found = _block(doc.data)
        if found is None:
            sep = "" if not doc.data or doc.data.endswith("\n\n") else (
                "\n" if doc.data.endswith("\n") else "\n\n")
            doc.data = doc.data + sep + value + "\n"
        else:
            doc.data = doc.data[:found[0]] + value + doc.data[found[1]:]
        return
    if kind == "rules":
        doc.data = value
        return
    node = doc.data
    for part in key[:-1]:
        node = node.setdefault(part, {})
    node[key[-1]] = value


def _delete(doc, kind: str, key: list) -> None:
    if kind == "global-block":
        found = _block(doc.data)
        if found is not None:
            start, end = found
            if doc.data[end:end + 1] == "\n":
                end += 1
            doc.data = doc.data[:start].rstrip("\n") + (
                "\n" if doc.data[:start].strip() else "") + doc.data[end:]
        return
    if kind == "rules":
        doc.data = ""
        return
    _prune(doc.data, key)


def _prune(node, key: list) -> None:
    """Delete `key` and every container the delete leaves empty."""
    if len(key) == 1:
        node.pop(key[0], None)
        return
    child = node.get(key[0])
    if isinstance(child, dict):
        _prune(child, key[1:])
        if not child:
            node.pop(key[0], None)


def _block(text: str):
    start = text.find("<!-- moxi loadout: from ")
    if start < 0:
        return None
    end = text.find(BLOCK_END, start)
    return None if end < 0 else (start, end + len(BLOCK_END))


def _members(doc, kind: str, key: list):
    if kind == "global-line":
        return doc.data.splitlines()
    node = doc.data
    for part in key[:-1]:
        node = node.get(part, {}) if isinstance(node, dict) else {}
    return node if isinstance(node, list) else []


def _member_add(doc, kind: str, key: list) -> None:
    if kind == "global-line":
        sep = "" if not doc.data or doc.data.endswith("\n") else "\n"
        doc.data = doc.data + sep + key[-1] + "\n"
        return
    node = doc.data
    for part in key[:-2]:
        node = node.setdefault(part, {})
    node.setdefault(key[-2], []).append(key[-1])


def _member_remove(doc, kind: str, key: list) -> None:
    if kind == "global-line":
        lines = doc.data.splitlines(keepends=True)
        doc.data = "".join(x for x in lines if x.rstrip("\r\n") != key[-1])
        return
    node = doc.data
    for part in key[:-2]:
        node = node.get(part, {})
    lst = node.get(key[-2], [])
    while key[-1] in lst:
        lst.remove(key[-1])
    if not lst:
        _prune(doc.data, key[:-1])


def _groups(doc, key: list) -> list:
    hooks = doc.data.get("hooks", {}) if isinstance(doc.data, dict) else {}
    groups = hooks.get(key[0], []) if isinstance(hooks, dict) else []
    return groups if isinstance(groups, list) else []


def _near(groups: list, matcher: str, command: str | None, skip=()):
    """A group with the matcher; with `command`, only one that holds it. A group in
    `skip` (another of loadout's records locates it) is never one."""
    for g in groups:
        if g in skip:
            continue
        if isinstance(g, dict) and (g.get("matcher") or "") == matcher:
            hooks = g.get("hooks") if isinstance(g.get("hooks"), list) else []
            if command is None or any(isinstance(x, dict) and x.get("command") == command
                                      for x in hooks):
                return g
    return None


def _other_groups(records: list, rec: dict) -> list:
    """The hook groups loadout's other records wrote in `rec`'s file, which an edit of
    `rec`'s group can't be."""
    return [x.get("written") for x in records if x is not rec and x.get("kind") == "hook"
            and x.get("file") == rec.get("file")]


def _command(group) -> str | None:
    hooks = group.get("hooks") if isinstance(group, dict) else None
    return hooks[0].get("command") if hooks and isinstance(hooks[0], dict) else None


def _plain(value):
    """An MCP value as compared: no `type`, no empty lists or tables."""
    if not isinstance(value, dict):
        return value
    return {k: v for k, v in value.items() if k != "type" and v not in ([], {}, None)}


# -- planning ------------------------------------------------------------------------------

def plan(manifest, folder, data: dict, *, claims=None) -> Run:
    """Every entry the manifest wants planned against the harness files and the ledger's
    `entries`. Reads, writes nothing."""
    from moxi import place

    run = Run()
    if manifest.exists and manifest.mode is None:
        run.notes.append("the global file is off: the manifest sets no [global] mode; "
                         "moxi loadout global mode MODE sets one")
    table, _ = place.harnesses()
    want, carried = wanted(manifest, folder, table, run)
    records = [r for r in data.get("entries", []) if isinstance(r, dict)
               and r.get("kind") not in KEPT_ELSEWHERE]
    claims = {} if claims is None else claims
    for where in want + [r for r in records
                         if (r.get("item"), r.get("harness")) not in carried]:
        _check_shape(run, where)
    used: set[int] = set()
    by_location: dict[tuple, Action] = {}
    for e in want:
        rec = next((i for i, r in enumerate(records) if i not in used and _same(r, e)),
                   None)
        if rec is not None:
            used.add(rec)
        first = by_location.get(e.location())
        if first is not None:
            if (e.value, e.sent) != (first.entry.value, first.entry.sent):
                run.actions.append(Action(e, None if rec is None else records[rec],
                                          "blocked", f"{first.entry.item} writes this key "
                                          "already"))
            else:
                run.actions.append(Action(e, None if rec is None else records[rec],
                                          first.op, first.reason, first.prior,
                                          replace=first.replace, follows=first))
            continue
        doc = _doc(run, e.file, e.kind)
        if doc is None:
            run.actions.append(Action(e, None if rec is None else records[rec], "stand",
                                      run.refused[e.file]))
            continue
        if e.kind == "mcp" and shutil.which(e.harness) is None:
            run.actions.append(Action(e, None if rec is None else records[rec], "stand",
                                      f"no {e.harness} on PATH, so its MCP servers are "
                                      "not written"))
            continue
        action = _one(e, None if rec is None else records[rec], doc, records,
                      _claimed(claims, e.ident(), e.harness))
        by_location[e.location()] = action
        run.actions.append(action)
    for i, r in enumerate(records):
        if i in used:
            continue
        if (r.get("item"), r.get("harness")) in carried:
            run.actions.append(Action(None, r, "stand"))
            continue
        doc = _doc(run, r.get("file", ""), r.get("kind", ""))
        if doc is None:
            run.actions.append(Action(None, r, "stand", run.refused.get(r.get("file"), "")))
            continue
        if r.get("kind") == "mcp" and shutil.which(r.get("harness", "")) is None:
            run.actions.append(Action(None, r, "stand", f"no {r.get('harness')} on PATH"))
            continue
        kind, _, name = str(r.get("item")).partition(":")
        run.actions.append(_gone(r, doc, records, used,
                                 _claimed(claims, (kind, name), r.get("harness")), want))
    return run


def _check_shape(run: Run, where: Entry | dict) -> None:
    """Refuse `where`'s file for its harness, with one line, when a node on the entry's
    path isn't the object or list loadout writes into: nothing in that file is written,
    and its entries stand."""
    get = (lambda k: getattr(where, k)) if isinstance(where, Entry) else where.get
    file, kind, key = get("file") or "", get("kind") or "", get("key") or []
    doc = _doc(run, file, kind)
    if doc is None or doc.kind != "json":
        return
    if kind == "hook":
        path, last = ["hooks", key[0]] if key else [], list
    elif kind in MEMBERS:
        path, last = key[:-1], list
    elif kind in ("opencode-permission", "opencode-mcp"):
        path, last = key[:-1], dict
    else:
        return
    node = doc.data
    for i, part in enumerate(path):
        node = node.get(part, _MISSING)
        if node is _MISSING:
            return
        want = last if i == len(path) - 1 else dict
        if not isinstance(node, want):
            shape = "a list" if want is list else "an object"
            line = (f"{doc.path}: {'.'.join(map(str, path[:i + 1]))} is not {shape}; "
                    "loadout leaves it, so its entries for this harness are not written")
            run.refused[file] = line
            run.lines.append(line)
            run.docs.pop(file, None)
            return


def _same(record: dict, e: Entry) -> bool:
    return (record.get("item"), record.get("harness"), record.get("file"),
            record.get("kind"), record.get("key")) == (e.item, e.harness, e.file, e.kind,
                                                        e.key)


def _claimed(claims: dict, ident: tuple[str, str], harness) -> bool:
    from moxi_loadout.manifest import parse_id

    hit = False
    for text in claims:
        try:
            i = parse_id(text) if not text.startswith("global:") else None
        except ValueError:
            continue
        if i is None:
            ok = ident == GLOBAL and text.rsplit("@", 1)[-1] in ("*", harness)
        elif ident[1] == "*":
            # The Codex rules file is every permissions item's: any of their ids names it.
            ok = i.kind == ident[0] and i.harness in ("*", harness)
        else:
            ok = (i.kind, i.name) == ident and i.harness in ("*", harness)
        if ok:
            claims[text] = hit = True
    return hit


def _shared_prior(records: list, e: Entry) -> bool:
    """A record finding an entry another item recorded takes that record's `prior`."""
    for r in records:
        if (r.get("file"), r.get("kind"), r.get("key")) == (e.file, e.kind, e.key):
            return bool(r.get("prior"))
    return True


def _one(e: Entry, rec, doc, records, claimed: bool) -> Action:
    value = e.sent if e.kind == "mcp" else e.value
    if e.kind in MEMBERS:
        if e.key[-1] in _members(doc, e.kind, e.key):
            return Action(e, rec, "ok", prior=rec.get("prior", False) if rec else
                          _shared_prior(records, e))
        return Action(e, rec, "add")
    if e.kind == "hook":
        groups = _groups(doc, e.key)
        if rec is not None:
            if rec.get("written") in groups:
                return Action(e, rec, "ok" if rec["written"] == e.value else "update",
                              prior=rec.get("prior", False))
            near = _near(groups, e.key[1], None, _other_groups(records, rec))
            if near is not None:
                if not claimed:
                    return Action(e, rec, "modified", f"edited; found {json.dumps(near)}")
                held = _near(groups, e.key[1], _command(rec.get("written")))
                return Action(e, rec, "update", replace=held if held is not None
                              else _MISSING)
        if e.value in groups:
            return Action(e, rec, "ok", prior=_shared_prior(records, e))
        near = _near(groups, e.key[1], _command(e.value))
        if near is not None:
            if not claimed:
                return Action(e, rec, "blocked", f"a group like it is there: "
                              f"{json.dumps(near)}; --replace takes it over")
            return Action(e, rec, "update", replace=near)
        return Action(e, rec, "add")
    found = _get(doc, e.kind, e.key)
    if rec is not None and found is not _MISSING:
        if found == rec.get("written"):
            old = rec.get("sent") if e.kind == "mcp" else rec.get("written")
            return Action(e, rec, "ok" if old == value else "update",
                          prior=rec.get("prior", False))
        if claimed:
            return Action(e, rec, "update")
        how = f" permissions:{e.by[0]}@codex" if e.kind == "rules" and e.by else ""
        return Action(e, rec, "modified", f"edited since loadout wrote it; --replace{how} "
                      "rewrites it")
    if found is _MISSING:
        return Action(e, rec, "add")
    equal = _plain(found) == _plain(value) if e.kind == "mcp" else found == value
    if equal:
        return Action(e, rec, "ok", prior=_shared_prior(records, e))
    if claimed:
        return Action(e, rec, "update")
    return Action(e, rec, "blocked", "something else is there; --replace takes it over")


def _gone(r: dict, doc, records: list, used: set, claimed: bool, want=()) -> Action:
    """A record no wanted entry names: its item was dropped or disabled. While another
    item still wants the same entry, the entry stays and only this record goes; when
    that item holds no record of it yet, this one is kept until it does."""
    kind, key, written = r.get("kind"), r.get("key") or [], r.get("written")
    if r.get("prior"):
        return Action(None, r, "end")
    others = [x for x in records if x is not r and (x.get("file"), x.get("kind"),
              x.get("key"), x.get("written")) == (r.get("file"), kind, key, written)]
    if any(records.index(x) in used for x in others):
        return Action(None, r, "end")
    if any((e.file, e.kind, e.key) == (r.get("file"), kind, key)
           and (e.sent == r.get("sent") if kind == "mcp" else e.value == written)
           for e in want):
        return Action(None, r, "end", shared=True)
    if kind in MEMBERS:
        present = key and key[-1] in _members(doc, kind, key)
        return Action(None, r, "remove" if present else "end")
    if kind == "hook":
        groups = _groups(doc, key)
        if written in groups:
            return Action(None, r, "remove")
        near = _near(groups, key[1] if len(key) > 1 else "", None, _other_groups(records, r))
        if near is None:
            return Action(None, r, "end")
        if not claimed:
            return Action(None, r, "modified", f"edited; found {json.dumps(near)}")
        held = _near(groups, key[1], _command(written))
        return Action(None, r, "remove", replace=held) if held is not None \
            else Action(None, r, "end")
    found = _get(doc, kind, key)
    if found is _MISSING:
        return Action(None, r, "end")
    if found == written or claimed:
        return Action(None, r, "remove")
    how = " permissions:NAME@codex, NAME any permissions item," if kind == "rules" else ""
    return Action(None, r, "modified", f"edited since loadout wrote it; --replace{how} "
                  "removes it")


# -- states and rows -----------------------------------------------------------------------

_PENDING = {"add": ("missing", ERROR), "update": ("stale", ERROR), "remove": ("stale", ERROR),
            "modified": ("modified", REFUSED), "blocked": ("blocked", REFUSED)}


def row(a: Action) -> Row:
    where = a.where
    get = (lambda k: getattr(where, k)) if isinstance(where, Entry) else where.get
    kind, _, name = str(get("item")).partition(":")
    if a.op in ("ok", "end", "stand") or a.done:
        state, code = ("ok", 0)
        if a.op == "stand" and a.reason:
            state, code = "blocked", REFUSED
    else:
        state, code = _PENDING[a.op]
    reason = a.reason
    if a.entry is None and a.op == "remove" and not a.done:
        reason = reason or "no longer wanted; install removes it"
    return Row(USER, kind, name, get("harness"), state, reason, get("file"), code)


def rows(run: Run) -> list[Row]:
    return list(run.rows) + [row(a) for a in run.actions if _shown(a)]


def covers(scope, a: Action) -> bool:
    """Whether a run's scope applies `a`: the global file only in a whole run or the
    global verbs; the rules file with any permission item."""
    where = a.where
    item = where.item if isinstance(where, Entry) else str(where.get("item"))
    kind, _, name = item.partition(":")
    if kind == "global":
        return scope.whole or scope.item == GLOBAL
    if scope.item == GLOBAL:
        return False
    if name == "*":
        return scope.covers(USER, kind, None) if scope.item is None else \
            scope.item[0] == kind and scope.covers(USER, kind, scope.item[1])
    return scope.covers(USER, kind, name)


# -- applying ------------------------------------------------------------------------------

def apply(run: Run, scope, data: dict, *, keep: int, say=print) -> list[Row]:
    """Carry the run's actions in `scope` out: CLI-backed MCP servers first, then one
    write per file. Updates the ledger's `entries` in `data`. Returns the rows in scope."""
    todo = [a for a in run.actions if covers(scope, a)
            and a.op in ("add", "update", "remove", "end", "ok")]
    # An action on an entry another item writes too follows that item's action; when
    # that item is out of scope, the first such action in scope is applied in its place.
    leading = {id(a) for a in todo if a.follows is None}
    stand_in: dict[int, Action] = {}
    followers: list[tuple[Action, Action]] = []
    for a in todo:
        if a.follows is None:
            continue
        if id(a.follows) in leading:
            followers.append((a, a.follows))
        elif id(a.follows) in stand_in:
            followers.append((a, stand_in[id(a.follows)]))
        else:
            stand_in[id(a.follows)] = a
    todo = [a for a in todo if a.follows is None or a in stand_in.values()]
    for a in todo:
        if (a.where.kind if a.entry else a.record.get("kind")) == "mcp" \
                and a.op in ("add", "update", "remove"):
            _cli(a, run, keep, say)
    by_file: dict[str, list[Action]] = {}
    for a in todo:
        kind = a.entry.kind if a.entry else a.record.get("kind")
        if kind == "mcp" or a.op in ("ok", "end"):
            a.done = a.done or a.op in ("ok", "end")
            continue
        by_file.setdefault(a.entry.file if a.entry else a.record.get("file"), []).append(a)
    for file, actions in by_file.items():
        doc = run.docs[file]
        for a in actions:
            _edit(doc, a)
        first = actions[0]
        harness = first.entry.harness if first.entry else first.record.get("harness")
        empty = doc.kind == "text" and any(
            (a.entry.kind if a.entry else a.record.get("kind")) in ("global-block", "rules",
                                                                    "global-line")
            for a in actions)
        problem = hz.write(doc, harness, keep, remove_empty=empty) if doc.changed else None
        if problem:
            run.lines.append(problem)
            continue
        for a in actions:
            a.done = True
            say(_said(a))
    for a, lead in followers:
        a.done, a.written = lead.done, lead.written
    _record(run, data, scope)
    return [row(a) for a in run.actions if covers(scope, a) and _shown(a)] + [
        r for r in run.rows if _row_covered(scope, r)]


def _row_covered(scope, r: Row) -> bool:
    if r.kind == "global":
        return scope.whole or scope.item == GLOBAL
    return scope.item != GLOBAL and scope.covers(USER, r.kind, r.name)


def _shown(a: Action) -> bool:
    return not ((a.op == "end" and a.entry is None) or (a.op == "stand" and not a.reason))


def _said(a: Action) -> str:
    where = a.where
    item = where.item if isinstance(where, Entry) else where.get("item")
    harness = where.harness if isinstance(where, Entry) else where.get("harness")
    file = where.file if isinstance(where, Entry) else where.get("file")
    verb = {"add": "wrote", "update": "updated", "remove": "removed"}[a.op]
    return f"{verb} {item.replace(':', ' ', 1)} for {harness} ({file})"


def _edit(doc, a: Action) -> None:
    e, r = a.entry, a.record
    kind = e.kind if e else r.get("kind")
    key = e.key if e else r.get("key")
    if kind in MEMBERS:
        if a.op == "add":
            _member_add(doc, kind, key)
        elif a.op == "remove":
            _member_remove(doc, kind, key)
        return
    if kind == "hook":
        hooks = doc.data.setdefault("hooks", {})
        groups = hooks.setdefault(key[0], [])
        old = a.replace if a.replace is not _MISSING else (r.get("written") if r else None)
        if old is not None and old in groups and a.op in ("update", "remove"):
            i = groups.index(old)
            if a.op == "remove":
                groups.pop(i)
            else:
                groups[i] = e.value
        elif a.op in ("add", "update"):
            groups.append(e.value)
        if not groups:
            _prune(doc.data, ["hooks", key[0]])
        return
    if a.op == "remove":
        _delete(doc, kind, key)
    else:
        _set(doc, kind, key, e.value)


def _cli(a: Action, run: Run, keep: int, say) -> None:
    """An MCP server through its harness's CLI: remove, then add; read back."""
    from moxi import proc

    e, r = a.entry, a.record
    harness = e.harness if e else r.get("harness")
    file = Path(e.file if e else r.get("file"))
    name = (e.key if e else r.get("key"))[-1]
    exe = shutil.which(harness)
    try:
        if file.exists():
            hz.backup(file, harness, file.read_bytes(), keep)
        steps = []
        if a.op in ("update", "remove"):
            steps.append([exe, "mcp", "remove"] + (["--scope", "user"] if harness ==
                                                   "claude" else []) + [name])
        if a.op in ("add", "update"):
            steps.append(_add_argv(exe, harness, name, e.sent))
        for argv in steps:
            done = proc.run(argv, timeout=CLI_SECONDS, input=None)
            if done.returncode != 0 and argv[2] in ("add", "add-json"):
                text = (done.stderr or b"").decode("utf-8", "replace").strip()
                raise RuntimeError(text.splitlines()[-1] if text else
                                   f"exit {done.returncode}")
    except Exception as exc:  # noqa: BLE001 - one server's failure is its own row
        run.lines.append(f"{harness} mcp {name}: {exc}")
        return
    try:
        view = _TomlView(file) if harness == "codex" else hz.Doc(file, "json")
        found = _get(view, "mcp", e.key if e else r.get("key"))
    except hz.Refused as exc:
        run.lines.append(f"{harness} mcp {name}: {exc}")
        return
    if a.op == "remove":
        if found is not _MISSING:
            run.lines.append(f"{harness} mcp {name}: still in {file} after mcp remove")
            return
    else:
        a.written = found
        if a.written is _MISSING:
            run.lines.append(f"{harness} mcp {name}: not found in {file} after the write")
            return
    a.done = True
    say(_said(a))


def mcp_there(record: dict) -> bool | None:
    """Whether the MCP server `record` names is in its file now; None when the file
    can't be read."""
    file = Path(record.get("file", ""))
    try:
        view = _TomlView(file) if record.get("harness") == "codex" else hz.Doc(file, "json")
    except hz.Refused:
        return None
    return _get(view, "mcp", record.get("key") or []) is not _MISSING


def _add_argv(exe, harness, name, sent) -> list[str]:
    if harness == "claude":
        return [exe, "mcp", "add-json", "--scope", "user", name, json.dumps(sent)]
    argv = [exe, "mcp", "add", name]
    if "url" in sent:
        return argv + ["--url", sent["url"]]
    for k, v in sent.get("env", {}).items():
        argv += ["--env", f"{k}={v}"]
    return argv + ["--", sent["command"], *sent.get("args", ())]


def _record(run: Run, data: dict, scope) -> None:
    """The ledger's `entries` after the run: a record per entry written, kept or taken,
    none for one removed or ended. Actions not applied keep their records as they were,
    and so do the records another part of loadout keeps (its ignore files)."""
    out = [r for r in data.get("entries", []) if isinstance(r, dict)
           and r.get("kind") in KEPT_ELSEWHERE]
    shared = []
    for a in run.actions:
        e, r = a.entry, a.record
        if not (a.done and covers(scope, a)):
            if r is not None:
                out.append(r)
            continue
        if a.shared:
            shared.append(r)
            continue
        if a.op in ("remove", "end") or e is None:
            continue
        written = a.written if e.kind == "mcp" else e.value
        if e.kind == "mcp" and a.op == "ok":
            written = r.get("written") if r else _get(run.docs[e.file], "mcp", e.key)
        rec = {"item": e.item, "harness": e.harness, "file": e.file, "kind": e.kind,
               "key": e.key, "written": written,
               "prior": bool(a.prior) if a.op == "ok" else False}
        if e.kind == "mcp":
            rec["sent"] = e.sent
        out.append(rec)
    # A dropped item's record of an entry another item still wants goes once that item
    # holds a record of it, so the entry is never left with none (the next run would
    # take it for the user's).
    where = ("file", "kind", "key", "written")
    for r in shared:
        if not any(x is not r and all(x.get(k) == r.get(k) for k in where) for x in out):
            out.append(r)
    data["entries"] = out


# -- the global file, shown ----------------------------------------------------------------

def preview(run: Run) -> dict[str, tuple[bytes, bytes]]:
    """What the next install would make of each global file: `{file: (now, then)}`."""
    import copy

    out = {}
    for a in run.actions:
        kind = a.entry.kind if a.entry else a.record.get("kind")
        if kind not in ("global-line", "global-block", "instructions"):
            continue
        file = a.entry.file if a.entry else a.record.get("file")
        doc = run.docs.get(file)
        if doc is None:
            continue
        if file not in out:
            out[file] = (doc.raw or b"", copy.deepcopy(doc))
        if a.op in ("add", "update", "remove"):
            _edit(out[file][1], a)
    return {f: (now, d.dumps() if not (d.kind == "text" and d.empty) else b"")
            for f, (now, d) in out.items()}


