"""Agent files for Codex and OpenCode, made from the Markdown agent file Claude reads.

Claude Code reads the agent file as it is. Codex reads a TOML file and OpenCode a Markdown
file of its own form, so loadout writes each into `STATE/loadout/generated/<harness>/` and
the placer places that file. Each conversion returns what it lost or derived ("dropped
tools", say), shown as notes.

A generated file carries a header naming its source and the SHA-256 of the rest of the
file. Rule: a generated file is rewritten only while its header's hash still matches its
bytes. A hand edit (made through the placed link, it lands here) reads `modified` and is
left alone until `install --replace` names it.

Frontmatter is read with PyYAML's `safe_load`.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from collections.abc import Mapping
from pathlib import Path

#: The harnesses an agent file is converted for, and each one's file suffix.
SUFFIX = {"codex": ".toml", "opencode": ".md"}
#: The suffix of the agent file Claude reads, and loadout's source form.
SOURCE_SUFFIX = ".md"

_HEADER = ("# generated by moxi loadout from {}; sha256 {}; edit the source, then run "
           "moxi loadout install\n")
_HEADER_RE = re.compile(r"# generated by moxi loadout from .*; sha256 ([0-9a-f]{64}); "
                        r"edit the source, then run moxi loadout install\n")
_WRITES = ("Edit", "Write")
_CONTROL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")


class FrontmatterError(ValueError):
    """A Markdown file has no frontmatter that reads as a mapping."""


def read(path: str | os.PathLike) -> tuple[dict, str]:
    """A Markdown file's YAML frontmatter and its body. Raises `OSError`, or
    `FrontmatterError` when the frontmatter is missing, unclosed or not a mapping."""
    import yaml

    text = Path(path).read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise FrontmatterError("has no frontmatter")
    head, sep, body = text[4:].partition("\n---\n")
    if not sep:
        raise FrontmatterError("has unclosed frontmatter")
    try:
        fields = yaml.safe_load(head)
    except yaml.YAMLError as exc:
        raise FrontmatterError(f"has frontmatter that isn't YAML ({_first_line(exc)})") \
            from None
    if not isinstance(fields, dict):
        raise FrontmatterError("has frontmatter that is not a mapping")
    return fields, body.lstrip("\n")


# -- the converters ------------------------------------------------------------------------

def codex(name: str, fields: Mapping, body: str, extra: Mapping | None) -> tuple[str, list[str]]:
    """The Codex agent TOML for agent `name`, its frontmatter `fields` and `body`, with the
    manifest's extra Codex keys `extra`; and what the conversion lost or derived."""
    fields, extra = dict(fields), dict(extra or {})
    notes = []
    denied = set(_tools(fields.pop("disallowedTools", None)))
    if "tools" in fields:
        allowed = set(_tools(fields.pop("tools")))
        denied |= {t for t in (*_WRITES, "Bash") if t not in allowed}
        notes.append("dropped tools")
    covered: set[str] = set()
    if all(t in denied for t in _WRITES) and "sandbox_mode" not in extra:
        extra["sandbox_mode"] = "read-only"
        notes.append("derived sandbox_mode = read-only")
    if extra.get("sandbox_mode") == "read-only":
        covered = set(_WRITES)
    notes += [f"widened tool {t}" for t in sorted(denied - covered)]
    if "isolation" in fields:
        notes.append(f"widened isolation: {fields.pop('isolation')}")
    description = fields.pop("description", "")
    fields.pop("name", None)
    notes += [f"dropped {k}" for k in fields]
    lines = [f"name = {_toml(name)}", f"description = {_toml(description)}"]
    lines += [f"{json.dumps(k)} = {_toml(v)}" for k, v in extra.items()]
    lines.append(f"developer_instructions = {_body(body)}")
    return "\n".join(lines) + "\n", notes


def opencode(name: str, fields: Mapping, body: str,
             extra: Mapping | None) -> tuple[str, list[str]]:
    """The OpenCode agent Markdown for agent `name`: `description` kept, `mode: subagent`
    unless the manifest's extra OpenCode keys `extra` say otherwise, those keys added; and
    what the conversion lost. Claude's tool names and model aliases don't carry over."""
    import yaml

    fields, extra = dict(fields), dict(extra or {})
    notes = []
    out = {"description": fields.pop("description", "")}
    fields.pop("name", None)
    if "tools" in fields or "disallowedTools" in fields:
        fields.pop("tools", None)
        fields.pop("disallowedTools", None)
        notes.append("dropped tools")
    notes += [f"dropped {k}" for k in fields]
    out["mode"] = "subagent"
    out.update(extra)
    head = yaml.safe_dump(out, sort_keys=False, allow_unicode=True)
    return f"---\n{head}---\n\n{body}", notes


CONVERTERS = {"codex": codex, "opencode": opencode}


# -- the header ----------------------------------------------------------------------------

def with_header(label: str, text: str) -> bytes:
    """A generated file's bytes: the header naming source `label` and the rest's hash.
    In a Markdown file the header goes on the frontmatter's first line, as a YAML comment,
    so the frontmatter still opens the file."""
    lead = ""
    if text.startswith("---\n"):
        lead, text = "---\n", text[4:]
    rest = (lead + text).encode("utf-8")
    header = _HEADER.format(label, hashlib.sha256(rest).hexdigest())
    return (lead + header + text).encode("utf-8")


def state(path: str | os.PathLike) -> str | None:
    """A generated file's state: None when it is missing or carries no header (not
    loadout's), `ok` when the header's hash matches, `modified` when it doesn't."""
    try:
        data = Path(path).read_bytes()
    except OSError:
        return None
    lead = b""
    if data.startswith(b"---\n"):
        lead, data = b"---\n", data[4:]
    first, _, rest = data.partition(b"\n")
    match = _HEADER_RE.fullmatch(first.decode("utf-8", "replace") + "\n")
    if match is None:
        return None
    digest = hashlib.sha256(lead + rest).hexdigest()
    return "ok" if digest == match.group(1) else "modified"


# -- helpers -------------------------------------------------------------------------------

def _tools(value) -> list[str]:
    if isinstance(value, str):
        return [t.strip() for t in value.split(",") if t.strip()]
    return [str(t) for t in value or []]


def _toml(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "[" + ", ".join(map(_toml, v)) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} = {_toml(x)}" for k, x in v.items()) + " }"
    return json.dumps(str(v), ensure_ascii=False)


def _body(text: str) -> str:
    """A multi-line literal string, or a basic string with escapes when a literal can't
    hold the text."""
    if "'''" in text or text.endswith("'") or _CONTROL.search(text) or "\r" in text:
        return json.dumps(text, ensure_ascii=False)
    return "'''\n" + text + "'''"


def _first_line(exc) -> str:
    return str(exc).splitlines()[0] if str(exc) else type(exc).__name__


