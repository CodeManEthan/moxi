"""The would-commit check, and the ignore files loadout writes in a work tree.

Rule: no placement loadout makes lands where git would commit it.

The core placer already refuses a target git tracks (cause `tracked`), which loadout shows
as `would-commit`. Whether ignore rules cover an untracked target is decided here, before
anything is placed and in `status`:

1. For each target folder, `git rev-parse --show-toplevel`, run from the folder's nearest
   existing ancestor, finds the work tree. Outside one there is nothing to do.
2. Per work tree, one `git check-ignore -z --stdin` over its targets. A target it doesn't
   name would be committed. git never names a tracked path, so a placed target that has
   since been tracked reads `would-commit` by the same call.
3. In a folder with no `.gitignore`, loadout writes one it owns before placing there, in a
   form that ignores itself: a header line `# generated by moxi loadout; sha256 <hash of
   the rest>`, `/.gitignore`, the placer's temporary and probe names, and `/<name>` for
   each loadout placement in the folder. It is recorded in the ledger's `entries` (kind
   `ignore-file`), rewritten as the placements change, and removed with the last one.
4. A folder whose `.gitignore` loadout didn't write, or whose loadout file has been edited
   (its hash differs), is left alone: the target isn't placed, it reads `would-commit`,
   and the line names the entry to add.

A target held in place (a project's own committed copy) is never checked.

Every git call runs through `moxi.proc.run` with a timeout and stdin closed, with git's
repository-local variables (`git rev-parse --local-env-vars`, asked once per run) and its
four pathspec variables removed from the environment, so a variable leaked from a git
hook can't aim the call at another repository.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path

IGNORE = ".gitignore"
#: The kind of an ignore file's record in the ledger's `entries`.
KIND = "ignore-file"
HEADER = "# generated by moxi loadout; sha256 {}\n"
_HEADER_RE = re.compile(r"# generated by moxi loadout; sha256 ([0-9a-f]{64})\n")
#: The lines every ignore file of loadout's holds: itself, and the placer's temporary
#: and probe names.
FIXED = ("/" + IGNORE, "/.*.moxi-tmp", "/.moxi-probe-*")
#: How long one git call may take, in seconds.
GIT_SECONDS = 30.0
#: git's pathspec variables, which change how a path given to git is read.
PATHSPEC_VARS = ("GIT_LITERAL_PATHSPECS", "GIT_GLOB_PATHSPECS", "GIT_NOGLOB_PATHSPECS",
                 "GIT_ICASE_PATHSPECS")
#: git's repository-local variables, removed even when `--local-env-vars` can't be asked.
LOCAL_VARS = ("GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_CONFIG", "GIT_CONFIG_PARAMETERS",
              "GIT_CONFIG_COUNT", "GIT_OBJECT_DIRECTORY", "GIT_DIR", "GIT_WORK_TREE",
              "GIT_IMPLICIT_WORK_TREE", "GIT_GRAFT_FILE", "GIT_INDEX_FILE",
              "GIT_NO_REPLACE_OBJECTS", "GIT_REPLACE_REF_BASE", "GIT_PREFIX",
              "GIT_SHALLOW_FILE", "GIT_COMMON_DIR")


# -- the file ------------------------------------------------------------------------------

def text(names) -> str:
    """An ignore file of loadout's for the placements `names`."""
    body = "".join(line + "\n" for line in FIXED + tuple(sorted("/" + n for n in names)))
    return HEADER.format(hashlib.sha256(body.encode()).hexdigest()) + body


def state(path: str | os.PathLike) -> str:
    """`absent`; `ours`, a file of loadout's as it wrote it; `edited`, one of loadout's
    whose hash no longer matches; `theirs`, anything else (a link included)."""
    path = os.fspath(path)
    if not os.path.lexists(path):
        return "absent"
    if os.path.islink(path) or not os.path.isfile(path):
        return "theirs"
    try:
        data = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return "theirs"
    first, _, body = data.partition("\n")
    m = _HEADER_RE.fullmatch(first + "\n")
    if m is None:
        return "theirs"
    return "ours" if hashlib.sha256(body.encode()).hexdigest() == m.group(1) else "edited"


def listed(path: str | os.PathLike) -> set[str]:
    """The placement names an ignore file of loadout's lists."""
    try:
        lines = Path(path).read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return set()
    return {x[1:] for x in lines[1:] if x.startswith("/") and x not in FIXED}


# -- git -----------------------------------------------------------------------------------

class GitError(Exception):
    """A git call that failed, or ran out of time (`timed_out`)."""

    def __init__(self, text: str, *, timed_out: bool = False):
        super().__init__(text)
        self.timed_out = timed_out


@dataclass
class Git:
    """loadout's own git calls for one run: each gets `timeout` seconds, and all of them
    together `budget` seconds when it is set (the doctor's), after which a call raises
    `GitError` without running."""

    timeout: float = GIT_SECONDS
    budget: float | None = None
    _env: dict | None = None
    _tops: dict = field(default_factory=dict)
    _start: float = field(default_factory=time.monotonic)

    def env(self) -> dict:
        if self._env is None:
            drop = set(LOCAL_VARS) | set(PATHSPEC_VARS)
            base = {k: v for k, v in os.environ.items() if k not in drop}
            try:
                done = self.run(["git", "rev-parse", "--local-env-vars"], None, base)
                drop |= set(done.stdout.decode("utf-8", "replace").split())
            except GitError:
                pass
            self._env = {k: v for k, v in os.environ.items() if k not in drop}
        return self._env

    def run(self, argv: list[str], input: bytes | None, env: dict | None = None):
        import subprocess

        from moxi import proc

        seconds = self.timeout
        if self.budget is not None:
            seconds = min(seconds, self.budget - (time.monotonic() - self._start))
            if seconds <= 0:
                raise GitError("loadout's time for git ran out", timed_out=True)
        try:
            return proc.run(argv, timeout=seconds, input=input,
                            env=self.env() if env is None else env)
        except subprocess.TimeoutExpired:
            raise GitError(f"git took longer than {seconds:.0f} s", timed_out=True) from None
        except OSError as exc:
            raise GitError(f"git can't be run ({exc})") from None

    def toplevel(self, folder: str) -> str | None:
        """The top of the work tree holding `folder` (or its nearest existing ancestor),
        or None outside one."""
        here = _existing(folder)
        if here not in self._tops:
            done = self.run(["git", "-C", here, "rev-parse", "--show-toplevel"], None)
            top = done.stdout.decode("utf-8", "surrogateescape").strip()
            self._tops[here] = os.path.normpath(top) if done.returncode == 0 and top \
                else None
        return self._tops[here]

    def ignored(self, top: str, paths: list[str]) -> set[str]:
        """Which of `paths` (relative to `top`) git ignores there."""
        data = b"".join(p.encode("utf-8", "surrogateescape") + b"\0" for p in paths)
        done = self.run(["git", "-C", top, "check-ignore", "-z", "--stdin"], data)
        if done.returncode not in (0, 1):
            err = (done.stderr or b"").decode("utf-8", "replace").strip()
            raise GitError(err.splitlines()[-1] if err else f"exit {done.returncode}")
        return {p.decode("utf-8", "surrogateescape") for p in done.stdout.split(b"\0") if p}


def _existing(folder: str) -> str:
    here = os.path.abspath(folder)
    while not os.path.isdir(here):
        parent = os.path.dirname(here)
        if parent == here:
            break
        here = parent
    return here


def _relative(target: str, top: str) -> str | None:
    """`target` relative to `top`, read through the real path of its folder (never of
    the target, which may be a link loadout placed)."""
    folder, name = os.path.split(os.path.abspath(target))
    here = _existing(folder)
    real = os.path.join(os.path.realpath(here), os.path.relpath(folder, here), name)
    rel = os.path.relpath(os.path.normpath(real), os.path.realpath(top))
    return None if rel == ".." or rel.startswith(".." + os.sep) else rel.replace(os.sep, "/")


# -- the check -----------------------------------------------------------------------------

@dataclass
class Verdict:
    """What the check says of one target: `ok` (ignored, or outside a work tree),
    `needs` (loadout's ignore file in `folder` covers it once written), `would-commit`
    (with the `line` to show) or `unchecked` (git ran out of time)."""

    state: str
    folder: str
    line: str = ""


def check(targets, git: Git | None) -> dict[str, Verdict]:
    """Each of `targets` (target keys) checked against git's ignore rules."""
    out: dict[str, Verdict] = {}
    if not targets:
        return out
    if git is None or shutil.which("git") is None:
        return {t: Verdict("ok", os.path.dirname(t)) for t in targets}
    trees: dict[str, list[tuple[str, str]]] = {}
    for t in dict.fromkeys(targets):
        folder = os.path.dirname(t)
        try:
            top = git.toplevel(folder)
        except GitError as exc:
            out[t] = Verdict("unchecked", folder, str(exc))
            continue
        rel = None if top is None else _relative(t, top)
        if rel is None:
            out[t] = Verdict("ok", folder)
        else:
            trees.setdefault(top, []).append((t, rel))
    for top, pairs in trees.items():
        try:
            ignored = git.ignored(top, [rel for _, rel in pairs])
        except GitError as exc:
            for t, _ in pairs:
                folder = os.path.dirname(t)
                state = "unchecked" if exc.timed_out else "would-commit"
                out[t] = Verdict(state, folder, f"git check-ignore in {top} failed "
                                 f"({exc}), so loadout can't tell whether git would "
                                 "commit it")
            continue
        for t, rel in pairs:
            folder = os.path.dirname(t)
            out[t] = Verdict("ok", folder) if rel in ignored else _uncovered(t, folder)
    return out


def _uncovered(target: str, folder: str) -> Verdict:
    """A target git would commit: what loadout's ignore file can do about it."""
    path = os.path.join(folder, IGNORE)
    name = os.path.basename(target)
    found = state(path)
    if found == "absent" or (found == "ours" and name not in listed(path)):
        return Verdict("needs", folder)
    if found == "ours":
        return Verdict("would-commit", folder, f"{path} ignores it, but git tracks it; "
                       f"git rm --cached it")
    if found == "edited":
        return Verdict("would-commit", folder, f"git would commit it; {path} was "
                       f"edited since loadout wrote it: add /{name} to it, or delete it "
                       "and run install again")
    return Verdict("would-commit", folder, f"git would commit it; add /{name} to {path}")


# -- the ignore files ----------------------------------------------------------------------

def records(data: dict) -> dict[str, dict]:
    """The ledger's ignore-file records, by file."""
    return {r["file"]: r for r in data.get("entries", [])
            if isinstance(r, dict) and r.get("kind") == KIND and isinstance(r.get("file"), str)}


def write(folder: str, names, data: dict, section, say) -> str | None:
    """Write loadout's ignore file in `folder` for `names`, and record it in `data`.
    Returns None, or the line saying why it wasn't written."""
    from moxi.files import atomic_write

    path = os.path.join(folder, IGNORE)
    found = state(path)
    if found not in ("absent", "ours"):
        return f"{path} is not loadout's; loadout leaves it"
    want = text(names)
    try:
        if found == "absent" or Path(path).read_text(encoding="utf-8") != want:
            os.makedirs(folder, exist_ok=True)
            atomic_write(path, want, mode=0o644)
            if found == "absent":
                say(f"wrote {path}")
    except OSError as exc:
        return f"{path} can't be written ({exc})"
    _record(data, path, want, section)
    return None


def _record(data: dict, path: str, written: str, section) -> None:
    entries = [r for r in data.get("entries", [])
               if not (isinstance(r, dict) and r.get("kind") == KIND and r.get("file") == path)]
    entries.append({"item": "ignore", "harness": "*", "file": path, "kind": KIND,
                    "key": [], "written": written, "prior": False, "section": section})
    data["entries"] = entries


def _drop(data: dict, path: str) -> None:
    data["entries"] = [r for r in data.get("entries", [])
                       if not (isinstance(r, dict) and r.get("kind") == KIND
                               and r.get("file") == path)]


def settle(data: dict, placements, folders=None, *, say) -> list[str]:
    """Bring each of loadout's ignore files in `folders` (every recorded one when None)
    into line with `placements` (the `moxi.place.Placed` loadout holds now): rewritten,
    or removed once nothing of loadout's is left in its folder. An ignore file edited
    since loadout wrote it is left as it is, its record kept; one whose header is gone is
    the user's, and its record is dropped. Returns the lines to show."""
    from moxi.place import IN_PLACE

    names: dict[str, set[str]] = {}
    for p in placements:
        if p.form != IN_PLACE:
            names.setdefault(os.path.dirname(str(p.path)), set()).add(p.path.name)
    lines = []
    recorded = records(data)
    for path, rec in recorded.items():
        folder = os.path.dirname(path)
        if folders is not None and folder not in folders:
            continue
        found = state(path)
        if found == "absent":
            _drop(data, path)
            continue
        if found == "theirs":
            # Without loadout's header the file is the user's (they may have folded
            # loadout's lines into their own): loadout forgets it and never removes it.
            _drop(data, path)
            say(f"{path} no longer has loadout's header, so loadout leaves it to you; "
                "put the header back as it was, or drop loadout's lines from it")
            continue
        if found != "ours":
            continue
        now = names.get(folder, set())
        if not now:
            try:
                os.unlink(path)
            except OSError as exc:
                lines.append(f"{path} can't be removed ({exc})")
                continue
            _drop(data, path)
            say(f"removed {path}")
            continue
        problem = write(folder, now, data, rec.get("section"), say)
        if problem:
            lines.append(problem)
    return lines


def problems(data: dict) -> list[tuple[str, str | None, str]]:
    """Each recorded ignore file that is no longer as loadout wrote it, with loadout's
    header still on it: its path, the section it serves, and why. (One whose header is
    gone is the user's; `settle` drops its record.)"""
    out = []
    for path, rec in records(data).items():
        found = state(path)
        if found == "edited":
            out.append((path, rec.get("section"), f"{path} was edited since loadout wrote "
                        "it; restore it, or delete it and run install again"))
    return out


