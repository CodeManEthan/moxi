"""Write `_folds.py`, the fold sets of private names, from the running CPython's re.

    uv run packages/secrets/tools/name_folds.py            # write src/moxi_secrets/_folds.py
    uv run packages/secrets/tools/name_folds.py --check    # exit 1 when it differs

Dev-only: it is not in the wheel or the sdist. Private names carry no case-insensitive flag
on either engine. Each character that Python's re folds under IGNORECASE to more than
itself is written as the class of its fold set, the same class on RE2 and on re, so both
engines match an entry at the same places. This tool finds those sets: for every character
Python could fold (one whose lower, upper, casefold or title case differs from it, and the
single characters those give), it matches `(?i)c` and `(?i)[c]` against all of them. A
pass of one case-insensitive class of them all over every code point confirms that nothing
outside folds into them.

Run it on the newest CPython: each Unicode version adds case pairs and has never taken one
away. It refuses to write a table from an older Unicode than the one `_folds.py` holds,
since that would drop letters. The bump tool runs `outside()` before the package's tests and
regenerates the table when the running Python folds a character outside it.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
TABLE = TOOLS.parent / "src" / "moxi_secrets" / "_folds.py"
WIDTH = 96


def _code_points() -> range:
    return range(0x110000)


def _text(cps) -> str:
    return "".join(chr(c) for c in cps if not 0xD800 <= c <= 0xDFFF)


def _escape(c: int) -> str:
    return "\\U%08x" % c


def candidates() -> set[int]:
    """Every character the running Python could fold to something else, and what it gives."""
    out: set[int] = set()
    for c in _code_points():
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        for mapped in (ch.lower(), ch.upper(), ch.casefold(), ch.title()):
            if mapped != ch:
                out.add(c)
                if len(mapped) == 1:
                    out.add(ord(mapped))
    # Anything outside the pool that a case-insensitive class of the pool matches folds
    # into it, so it joins the pool. Repeat until nothing new comes.
    everything = _text(_code_points())
    while True:
        rx = re.compile("(?i)[" + "".join(_escape(c) for c in sorted(out)) + "]")
        more = {ord(m.group()) for m in rx.finditer(everything)} - out
        if not more:
            return out
        out |= more


def python_folds() -> dict[int, frozenset[int]]:
    """{character: its IGNORECASE fold set} under the running Python's re, for every
    character that folds to more than itself."""
    pool = sorted(candidates())
    text = _text(pool)
    out = {}
    for c in pool:
        literal = {ord(m.group()) for m in re.finditer("(?i)" + _escape(c), text)}
        in_class = {ord(m.group()) for m in re.finditer("(?i)[" + _escape(c) + "]", text)}
        if literal != in_class:
            raise SystemExit(f"U+{c:04X}: the literal and the class fold differently")
        if literal != {c}:
            out[c] = frozenset(literal)
    return out


def groups(folds: dict[int, frozenset[int]]) -> list[tuple[int, ...]]:
    """The distinct fold sets, each sorted. Each must be an equivalence class: every member
    folds to exactly the set."""
    out = sorted({tuple(sorted(s)) for s in folds.values()})
    for group in out:
        for c in group:
            if folds.get(c) != frozenset(group):
                raise SystemExit(f"U+{c:04X}: its fold set is not its group's; the table "
                                 "cannot write one class per character")
    return out


def render(found: list[tuple[int, ...]], unicode: str) -> str:
    """The source of `_folds.py` for these groups."""
    body = " ".join("".join(chr(c) for c in g) for g in found)
    lines, line = [], ""
    for word in body.split(" "):
        piece = ascii(word + " ")[1:-1]
        if line and len(line) + len(piece) > WIDTH - 8:
            lines.append(line)
            line = ""
        line += piece
    lines.append(line)
    lines[-1] = lines[-1].removesuffix(" ")
    joined = "\n".join(f'    "{x}"' for x in lines)
    return f'''"""Generated by tools/name_folds.py; do not edit.

The fold sets of private names: each group is a set of characters CPython's re treats as
equal under IGNORECASE, on Unicode {unicode}. A character in no group folds only to
itself. Private names write each character in a group as the class of its group, on both
engines, and carry no case-insensitive flag.
"""

#: The Unicode version the table was generated on.
UNICODE = "{unicode}"

_GROUPS = (
{joined}
)

#: Each character in a group, mapped to its whole group.
FOLDS: dict[str, str] = {{c: g for g in _GROUPS.split(" ") for c in g}}
'''


def table() -> dict[str, str]:
    """The committed table, read from the file (not imported, so a fresh copy each time)."""
    scope: dict = {}
    exec(compile(TABLE.read_text("utf-8"), str(TABLE), "exec"), scope)
    return scope["FOLDS"]


def table_unicode() -> str:
    found = re.search(r'^UNICODE = "([\d.]+)"$', TABLE.read_text("utf-8"), re.M)
    return found.group(1) if found else "0"


def outside(folds: dict[int, frozenset[int]], held: dict[str, str]) -> list[int]:
    """The characters whose fold under the running Python reaches past their set in
    `held`: on this Python a guard's IGNORECASE match of them would be missed."""
    return sorted(c for c, s in folds.items()
                  if not {chr(x) for x in s} <= set(held.get(chr(c), chr(c))))


def _version(text: str) -> tuple[int, ...]:
    return tuple(int(x) for x in text.split("."))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="name_folds.py", description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 when _folds.py differs from a fresh one")
    args = parser.parse_args(argv)
    unicode = unicodedata.unidata_version
    found = groups(python_folds())
    source = render(found, unicode)
    current = TABLE.read_text("utf-8") if TABLE.exists() else ""
    say = f"{len(found)} groups over {sum(map(len, found))} characters, Unicode {unicode}"
    if args.check:
        if current != source:
            print(f"{TABLE.name} differs from a fresh generation ({say})", file=sys.stderr)
            return 1
        print(f"{TABLE.name} is current: {say}")
        return 0
    if current and _version(unicode) < _version(table_unicode()):
        print(f"this Python has Unicode {unicode}, older than the table's {table_unicode()}: "
              "run the tool on a newer CPython", file=sys.stderr)
        return 2
    from moxi import files

    files.atomic_write(TABLE, source, mode=0o644)
    print(f"wrote {TABLE.name}: {say}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
